"""SQLite federation for node-wide reads; shop writes keep independent transactions."""

import contextvars, re, sqlite3
from contextlib import ExitStack
from .database_writer import connection

shop_context = contextvars.ContextVar("business_shop", default=None)


class Result:
    def __init__(self, rows=(), rowcount=0, lastrowid=None, description=None):
        self.rows = iter(rows)
        self.rowcount = rowcount
        self.lastrowid = lastrowid
        self.description = description

    def fetchone(self):
        return next(self.rows, None)

    def fetchall(self):
        return list(self.rows)

    def fetchmany(self, size=1):
        result = []
        for _ in range(size):
            row = self.fetchone()
            if row is None:
                break
            result.append(row)
        return result

    def __iter__(self):
        return self.rows


class FederatedConnection:
    def __init__(self, store, immediate=False, timeout=60):
        self.store = store
        self.manager = store._shards
        self.immediate = immediate
        self.timeout = timeout
        self.stack = ExitStack()
        self.connections = {}
        self.functions = []
        self.collations = []
        self.scope = shop_context.get()
        self.current = None

    def __enter__(self):
        return self

    def __exit__(self, *args):
        return self.stack.__exit__(*args)

    def db(self, sid=None):
        if sid not in self.connections:
            path = self.store.path if sid is None else self.manager.path(sid)
            self.connections[sid] = self.stack.enter_context(
                connection(path, self.timeout, immediate=self.immediate and sid is not None)
            )
            for args, kwargs in self.functions:
                self.connections[sid].create_function(*args, **kwargs)
            for args in self.collations:
                self.connections[sid].create_collation(*args)
        return self.connections[sid]

    def create_function(self, *args, **kwargs):
        self.functions.append((args, kwargs))
        for db in self.connections.values():
            db.create_function(*args, **kwargs)

    def create_collation(self, *args):
        self.collations.append(args)
        for db in self.connections.values():
            db.create_collation(*args)

    def cursor(self):
        return self

    def executescript(self, sql):
        return self.db().executescript(sql)

    def infer(self, sql, params, table):
        # Bound values only; literal shop filters are also generated by local queries.
        matches = list(re.finditer(r"\bshop_id\s*=\s*(\?|[0-9]+)", sql, re.I))
        ids = set()
        for m in matches:
            index = sql[: m.start(1)].count("?")
            value = params[index] if m[1] == "?" else int(m[1])
            if type(value) is int:
                ids.add(value)
        if len(ids) == 1:
            return ids.pop()
        if re.match(r"\s*(INSERT|REPLACE)", sql, re.I):
            m = re.search(
                r'\b(?:INTO)\s+["\[]?' + re.escape(table) + r'["\]]?\s*(?:\(([^)]*)\))?\s*VALUES\s*\(([^)]*)\)',
                sql,
                re.I,
            )
            if m:
                columns = [v.strip(' "[]') for v in m[1].split(",")] if m[1] else self.manager.columns[table]
                if "shop_id" in columns:
                    values = m[2].split(",")
                    pos = columns.index("shop_id")
                    v = values[pos].strip()
                    if v == "?":
                        return int(params[sql[: m.start(2)].count("?") + sum(x.count("?") for x in values[:pos])])
                    if v.isdigit():
                        return int(v)
        return (
            self.scope
            if self.scope is not None
            else self.current
            if table == "order_clock" or "temp.table_name_goods" in sql or re.search(r"\bordinal\s*=", sql, re.I)
            else None
        )

    def execute(self, sql, parameters=()):
        params = tuple(parameters)
        upper = sql.strip().upper()
        if upper.startswith(("BEGIN", "COMMIT", "ROLLBACK", "END", "SAVEPOINT", "RELEASE")):
            # Commit/rollback remains owned by the surrounding context.
            if upper.startswith("BEGIN"):
                self.immediate = "IMMEDIATE" in upper
            return Result()
        if upper.startswith("CREATE TEMP"):
            return self.db(self.scope or self.current).execute(sql, params)
        if upper.startswith(("PRAGMA", "CREATE", "ALTER", "DROP")) or "sqlite_master" in sql:
            return self.db().execute(sql, params)
        touched = [t for t in self.manager.tables if re.search(r"\b" + re.escape(t) + r"\b", sql)]
        if not touched:
            match = re.search(r"order-open-scan:(\d+):", str(params))
            target = int(match[1]) if match else (self.scope or self.current) if "table_name" in sql else None
            return self.db(target).execute(sql, params)
        sid = self.infer(sql, params, touched[0])
        write = not upper.startswith(("SELECT", "EXPLAIN", "WITH"))
        if upper.startswith("WITH") and re.search(r"\b(INSERT|UPDATE|DELETE|REPLACE)\b", upper):
            raise ValueError("不支持隐式跨店 CTE 写入")
        if sid == 0:
            return self.db().execute(sql, params)
        if sid is not None and sid > 0:
            self.current = sid
            # Node metadata joins use a read-only attachment; writes stay in main.
            db = self.db(sid)
            if not getattr(db, "node_attached", False):
                db.execute("ATTACH DATABASE ? AS node", (self.store.path.resolve().as_uri() + "?mode=ro",))
                db.node_attached = True
            from .shop_storage import MANAGEMENT

            rewritten = sql
            for table in MANAGEMENT - {"settings"}:
                rewritten = re.sub(r"(?<![.\w])" + re.escape(table) + r"\b", "node." + table, rewritten)
            return db.execute(rewritten, params)
        if write:
            if upper.startswith(("INSERT", "REPLACE")):
                raise ValueError("业务写入必须指定店铺，已拒绝跨店写入")
            raise ValueError("业务更新必须显式指定店铺，已拒绝非原子跨店写入")
        return self.read_all(sql, params, touched)

    def executemany(self, sql, parameters):
        count = 0
        last = None
        for values in parameters:
            result = self.execute(sql, values)
            count += result.rowcount
            last = result.lastrowid
        return Result(rowcount=count, lastrowid=last)

    def read_all(self, sql, params, touched):
        # Aggregate reads remain supported, but observable for migration to explicit APIs.
        import logging, time

        now = time.monotonic()
        last = getattr(self.store, "_federated_read_warning", -float("inf"))
        self.store._federated_read_count = getattr(self.store, "_federated_read_count", 0) + 1
        if now - last >= 60:
            self.store._federated_read_warning = now
            logging.getLogger(__name__).warning(
                "跨店汇总读取：%d 个店铺库，累计 %d 次", len(self.manager.paths), self.store._federated_read_count
            )
        # Federate only referenced columns. Header polling never copies large payloads.
        db = sqlite3.connect(":memory:")
        db.row_factory = sqlite3.Row
        try:
            for args, kwargs in self.functions:
                db.create_function(*args, **kwargs)
            for args in self.collations:
                db.create_collation(*args)
            node = self.db()
            all_tables = {
                r[0]: r[1]
                for r in node.execute(
                    "SELECT name,sql FROM sqlite_master WHERE type='table' AND sql IS NOT NULL AND name NOT LIKE 'sqlite_%'"
                )
            }
            tables = [t for t in all_tables if re.search(r"\b" + re.escape(t) + r"\b", sql)]
            wildcard = bool(re.search(r"(?:SELECT\s+|\w\.)(?:\*)", sql, re.I))
            for table in tables:
                schema = list(node.execute('PRAGMA table_info("' + table + '")'))
                columns = [r[1] for r in schema]
                needed = columns if wildcard else [c for c in columns if re.search(r"\b" + re.escape(c) + r"\b", sql)]
                if not needed:
                    needed = columns[:1]
                # No constraints here: distinct store-local operational ids may overlap.
                db.execute('CREATE TABLE "' + table + '" (' + ",".join('"' + r[1] + '" ' + r[2] for r in schema) + ")")
                names = ",".join('"' + c + '"' for c in needed)
                sources = [self.db(s) for s in self.manager.paths] if table in self.manager.tables else [node]
                if table in ("data_changes", "data_versions"):
                    sources.append(node)
                for source in sources:
                    cursor = source.execute(
                        "SELECT "
                        + names
                        + ' FROM "'
                        + table
                        + '"'
                        + (
                            " WHERE shop_id=0"
                            if source is node and table in self.manager.tables and table != "order_clock"
                            else ""
                        )
                    )
                    while rows := cursor.fetchmany(500):
                        db.executemany(
                            'INSERT INTO "' + table + '" (' + names + ") VALUES(" + ",".join("?" for _ in needed) + ")",
                            rows,
                        )
            cursor = db.execute(sql, params)
            return Result(cursor.fetchall(), description=cursor.description)
        finally:
            db.close()
