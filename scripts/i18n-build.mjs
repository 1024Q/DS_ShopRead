// Regenerate app/i18n/zh-TW.mjs (Simplified → Traditional Chinese converter data).
//
//   python scripts/i18n-extract.py > tmp/i18n-corpus.json
//   npm install --no-save opencc-js@1.0.5   (dev-time only, not a runtime dependency)
//   node scripts/i18n-build.mjs tmp/i18n-corpus.json
//
// OpenCC (cn → tw) converts every CJK character once to build a character map;
// only multi-character exceptions found in the UI strings are kept as phrases.
// The browser then converts any UI text with this small table instead of
// shipping one entry per string (≈700 KB before, ≈20 KB now).
import fs from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const OpenCC = require(process.env.OPENCC_JS || 'opencc-js');
const convert = OpenCC.Converter({ from: 'cn', to: 'tw' });
const corpus = JSON.parse(fs.readFileSync(process.argv[2] || 'tmp/i18n-corpus.json', 'utf8'));
const texts = [...corpus.exact, ...corpus.patterns];

let chars = '';
const map = new Map();
for (let code = 0x3400; code <= 0x9fff; code++) {
  const source = String.fromCharCode(code);
  const target = convert(source);
  if (target !== source && target.length === 1) {
    chars += source + target;
    map.set(source, target);
  }
}

const phrases = new Map();
let longest = 1;
function run(text) {
  let out = '';
  for (let i = 0; i < text.length;) {
    let hit = false;
    for (let n = Math.min(longest, text.length - i); n >= 2; n--) {
      const value = phrases.get(text.slice(i, i + n));
      if (value !== undefined) {
        out += value;
        i += n;
        hit = true;
        break;
      }
    }
    if (!hit) {
      out += map.get(text[i]) ?? text[i];
      i++;
    }
  }
  return out;
}
// Add the smallest phrase that fixes the first differing character, repeat.
// OpenCC output that changes length or cannot be expressed as a short phrase is
// left to the character map (it was already a near-identical spelling).
let unresolved = 0;
for (const text of texts) {
  const want = convert(text);
  if (want.length !== text.length) continue;
  for (let guard = 0; guard < 20; guard++) {
    const got = run(text);
    if (got === want) break;
    let i = 0;
    while (got[i] === want[i]) i++;
    let added = false;
    for (let n = 2; n <= 6 && !added; n++)
      for (let a = Math.max(0, i - n + 1); a <= i && a + n <= text.length && !added; a++) {
        const sub = text.slice(a, a + n);
        if (phrases.has(sub)) continue;
        const value = convert(sub);
        if (value === want.slice(a, a + n) && value !== [...sub].map((c) => map.get(c) ?? c).join('')) {
          phrases.set(sub, value);
          longest = Math.max(longest, n);
          added = true;
        }
      }
    if (!added) {
      unresolved++;
      break;
    }
  }
}
const header =
  '// Generated by scripts/i18n-build.mjs (OpenCC cn → tw character map plus phrase exceptions).\n' +
  '// Do not edit by hand; re-run the generator after changing UI text.\n';
fs.writeFileSync(
  'app/i18n/zh-TW.mjs',
  header + 'export default ' + JSON.stringify({ chars, phrases: Object.fromEntries([...phrases].sort()) }) + ';\n',
);
console.log(
  `zh-TW: ${map.size} characters, ${phrases.size} phrases, ${unresolved} texts differ from OpenCC context rules`,
);
